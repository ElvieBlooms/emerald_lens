#!/usr/bin/env python3
"""Dump every text label from a local pret clone to a Lua table: the
.string labels in data/, and the u8 X[] = _("...") strings in src/ and
include/ (gText_Son, gText_Birch_BoyOrGirl and others live there).

    python3 pret_strings.py <pokefirered|pokeemerald|pokeruby clone> <out.lua>

The output holds the games' own text, so keep it out of the repo (it goes
to a path you choose; tools/wording/.gitignore ignores *.out.lua). check.lua
reads it to find hashes and check entries. -Elvie
"""
import glob
import os
import re
import sys

LABEL = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)::?\s*(?:@.*)?$')
STRING = re.compile(r'^\s*\.string\s+"((?:[^"\\]|\\.)*)"\s*(?:@.*)?$')
# const u8 gText_Son[] = _("son"); and the like, the text possibly split
# over several "..." pieces and lines
C_STRING = re.compile(r'\bu8\s+([A-Za-z_][A-Za-z0-9_]*)\s*\[[^\]]*\]\s*=\s*_\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\)')
C_PIECE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def lua_quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    root, out = sys.argv[1], sys.argv[2]
    texts, order = {}, []
    paths = []
    for ext in ('inc', 's'):
        paths += glob.glob(os.path.join(root, 'data', '**', '*.' + ext), recursive=True)
    for path in sorted(paths):
        label = None
        with open(path, encoding='utf-8', errors='replace') as f:
            for line in f:
                line = line.rstrip('\n')
                if line and not line[0].isspace():
                    m = LABEL.match(line.strip())
                    label = m.group(1) if m else None
                    continue
                m = STRING.match(line)
                if label and m:
                    if label not in texts:
                        texts[label] = ''
                        order.append(label)
                    # pret escapes: \" is a quote; \n \l \p stay as written
                    texts[label] += m.group(1).replace('\\"', '"')
    c_paths = []
    for sub in ('src', 'include'):
        for ext in ('c', 'h'):
            c_paths += glob.glob(os.path.join(root, sub, '**', '*.' + ext), recursive=True)
    for path in sorted(c_paths):
        with open(path, encoding='utf-8', errors='replace') as f:
            source = f.read()
        for m in C_STRING.finditer(source):
            label = m.group(1)
            if label in texts:
                continue
            texts[label] = ''.join(p.replace('\\"', '"') for p in C_PIECE.findall(m.group(2)))
            order.append(label)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('-- generated by pret_strings.py from %s; game text, keep out of the repo\n'
                % os.path.basename(os.path.abspath(root)))
        f.write('return {\n')
        for label in order:
            f.write('  [%s] = %s,\n' % (lua_quote(label), lua_quote(texts[label])))
        f.write('}\n')
    print('%d strings -> %s' % (len(order), out))


if __name__ == '__main__':
    main()
